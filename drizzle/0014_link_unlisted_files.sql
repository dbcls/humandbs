CREATE TEMP TABLE "dataset_files" AS
SELECT p."dataset_id", array_agg(DISTINCT l."file_name") AS "files"
FROM "file_link" AS l JOIN "label_pin" AS p ON p."kind" = 'dataset' AND p."label" = l."dataset_label"
GROUP BY p."dataset_id";--> statement-breakpoint
CREATE FUNCTION pg_temp.with_files(content jsonb, files text[]) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$
  SELECT jsonb_set(content, '{fileSelection}', (
    SELECT coalesce(jsonb_agg(n ORDER BY n COLLATE "C"), '[]'::jsonb)
    FROM (SELECT jsonb_array_elements_text(coalesce(content->'fileSelection', '[]'::jsonb)) AS n UNION SELECT unnest(files)) AS u
  ))
$$;--> statement-breakpoint
